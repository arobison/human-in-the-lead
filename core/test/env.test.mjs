test('three leases at once get distinct worktrees and ports, and release cleanly', async () => {
  const repoRoot = makeRepo();
  const { env, store, range } = await makeEnv({
    repoRoot,
    env: { worktree_setup: ['echo "set up for $PWD" > setup.txt'] },
  });
  const holders = ['D-1', 'D-2', 'D-3'];
  const got = await Promise.all(
    holders.map(async (holder, i) => {
      const wt = await env.createWorktree({ holder, itemId: `W-${i + 1}`, slug: `Task ${i + 1}!` });
      const port = await env.leasePort({ holder });
      const setup = await env.runSetup({ holder });
      return { holder, wt, port, setup };
    }),
  );

  assert.equal(new Set(got.map((g) => g.wt.lease.path)).size, 3);
  assert.equal(new Set(got.map((g) => g.wt.lease.branch)).size, 3);
  assert.equal(new Set(got.map((g) => g.port.lease.port)).size, 3);
  for (const g of got) {
    assert.ok(g.port.lease.port >= range.min && g.port.lease.port <= range.max);
    assert.ok(g.setup.ok);
    assert.match(g.wt.lease.branch, /^hitld\/W-\d-task-\d$/);
    assert.equal(
      readFileSync(join(g.wt.lease.path, 'setup.txt'), 'utf8').trim(),
      `set up for ${shellPath(g.wt.lease.path)}`,
    );
    // cut from the tip of main
    assert.equal(git(['rev-parse', 'HEAD'], g.wt.lease.path), git(['rev-parse', 'main'], repoRoot));
    // outside the repository, in the private store
    assert.ok(g.wt.lease.path.startsWith(store.root));
  }
  // asking again returns the same lease
  const again = await env.createWorktree({ holder: 'D-1', itemId: 'W-1' });
  assert.equal(again.existing, true);
  assert.equal((await env.leasePort({ holder: 'D-1' })).lease.port, got[0].port.lease.port);

  for (const g of got) {
    const r = await env.releaseHolder({ holder: g.holder, result: 'merged' });
    assert.equal(r.worktree.branch_deleted, true);
    assert.equal(r.port.released, true);
    assert.ok(!existsSync(g.wt.lease.path));
  }
  assert.deepEqual(env.registry().worktrees, {});
  assert.deepEqual(env.registry().ports, {});
  assert.equal(git(['branch', '--list', 'hitld/*'], repoRoot).trim(), '');
});

