/**
 * Record dispatches as the run module does: dispatched (with a real linked worktree of the primary
 * checkout), then claimed (and reported, if finished).
 * @param {import('../lib/store/store.mjs').PrivateStore} store
 * @param {{ id: string, role: string, claimed?: boolean, finished?: boolean, noWorktree?: boolean }[]} list
 * @param {{ repoRoot?: string, run?: Run }} [options]
 */
function dispatchesIn(store, list, options = {}) {
  const repoRoot = options.repoRoot ?? repoOf.get(store.root);
  const run = options.run ?? startRun(store, { session: 's1', host: 'h1' });
  for (const d of list) {
    let worktree;
    if (!d.noWorktree) {
      const path = join(dir('dispatch'), d.id);
      git(['worktree', 'add', '-q', '-b', `test/${d.id}-${counter}`, path, 'main'], repoRoot);
      worktree = real(path);
      wtPaths.set(`${store.root}|${d.id}`, worktree);
    }
    run.record({
      id: `dispatched-${d.id}`,
      event: 'dispatched',
      dispatch: d.id,
      item: 'W-1',
      tier: 1,
      role: d.role,
      host: run.host,
      ...(worktree ? { worktree } : {}),
    });
    if (d.claimed !== false) {
      run.record({
        id: `started-${d.id}`,
        event: 'started',
        dispatch: d.id,
        item: 'W-1',
        harness: 'fake',
        harness_ref: `ref-${d.id}`,
        host: run.host,
      });
    }
    if (d.finished) {
      run.record({
        id: `reported-${d.id}`,
        event: 'reported',
        dispatch: d.id,
        item: 'W-1',
        result: 'done',
      });
    }
  }
  return run;
}

