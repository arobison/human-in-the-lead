#!/usr/bin/env node
// The build step that makes the Claude Code plugin self-contained (design part 16.1). Installed
// plugins are copied to a cache and cannot reach files outside their directory, so the plugin gets
// its own copy of core/ (without tests), schemas/, templates/ and evals/, the skills from skills/
// with Claude Code front matter added, the agents from agents/ with the same, and the executor
// agents generated from the tier defaults.
//
//   node core/lib/packaging/build.mjs          write the plugin
//   node core/lib/packaging/build.mjs --check  only say what is out of date (exit 1 if anything)
//
// The output is committed, because a marketplace serves the plugin from the repository as it is.
// A test runs the check, so a change to core/ without a build fails `npm test`.

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { policyDefaults } from '../policy/policy.mjs';
import { MODEL_CLASSES } from '../../harness/claude-code/capabilities.mjs';

export const REPO = fileURLToPath(new URL('../../../', import.meta.url));
export const PLUGIN = join(REPO, 'plugins', 'human-in-the-lead');

/** Copied as they are, relative to the repository root. */
const COPIED = ['core/bin', 'core/lib', 'core/harness', 'schemas', 'templates', 'evals'];
/** Generated directories the build owns entirely. */
const OWNED = [...COPIED, 'skills', 'agents'];

/** Claude Code front matter added to each skill (design part 15.2: harness fields come from packaging). */
const SKILL_EXTRAS = /** @type {Record<string, Record<string, string>>} */ ({
  orchestrate: { 'argument-hint': '[start | resume]' },
  execute: { 'user-invocable': 'false' },
});

/**
 * Claude Code front matter added to each agent from agents/. The generalizer works only on what its
 * prompt holds: Read is the narrowest tool list that is not empty. The subagent documentation
 * (https://code.claude.com/docs/en/sub-agents.md, read 2026-11-14) documents no form for no tools:
 * an absent list inherits every tool, and a list where nothing resolves fails to launch.
 */
const AGENT_EXTRAS = /** @type {Record<string, Record<string, string>>} */ ({
  generalizer: { tools: 'Read', model: 'inherit' },
});

/** @param {string} dir @returns {string[]} files under dir, relative to it */
function walk(dir) {
  if (!existsSync(dir)) return [];
  /** @type {string[]} */
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full).map((f) => join(name, f)));
    else if (name !== '.DS_Store') out.push(name);
  }
  return out;
}

/** Add front matter keys after the existing ones. @param {string} text @param {Record<string, string>} extra */
function withFrontMatter(text, extra) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!m) throw new Error('a skill or agent must start with front matter');
  const lines = Object.entries(extra).map(([k, v]) => `${k}: ${v}`);
  return `---\n${m[1]}\n${lines.join('\n')}\n---\n${text.slice(m[0].length)}`;
}

/** The executor agent for a tier, from the policy defaults. @param {1 | 2} tier */
function agent(tier) {
  const t = policyDefaults().tiers[String(tier)];
  const model = MODEL_CLASSES[/** @type {keyof typeof MODEL_CLASSES} */ (t.model)] ?? 'inherit';
  return [
    '---',
    `name: executor-tier${tier}`,
    `description: A human-in-the-lead executor for tier-${tier} work items (${tier === 1 ? 'mechanical, fully specified' : 'implementation inside a known plan'}). Dispatched by the orchestrator with a brief; not for direct use.`,
    `model: ${model}`,
    `effort: ${t.effort}`,
    'isolation: worktree',
    'background: true',
    '---',
    '',
    'You are an executor. Your prompt is a brief from the orchestrator: it names one work item, your',
    'dispatch ID and your branch. Follow the execute skill of the human-in-the-lead plugin and the',
    'executor contract in AGENTS.md. Your final message is the report in the fixed shape, and',
    'nothing else.',
    '',
    '(The model and effort here are the tier defaults; the orchestrator passes the project policy',
    "values with each dispatch. Generated by core/lib/packaging/build.mjs; don't edit.)",
    '',
  ].join('\n');
}

/** Every file the build produces: plugin-relative path to content. @returns {Map<string, Buffer | string>} */
export function expectedFiles() {
  /** @type {Map<string, Buffer | string>} */
  const files = new Map();
  for (const dir of COPIED) {
    for (const f of walk(join(REPO, dir)))
      files.set(join(dir, f), readFileSync(join(REPO, dir, f)));
  }
  for (const name of readdirSync(join(REPO, 'skills')).sort()) {
    const src = join(REPO, 'skills', name, 'SKILL.md');
    if (!existsSync(src)) continue;
    files.set(
      join('skills', name, 'SKILL.md'),
      withFrontMatter(readFileSync(src, 'utf8'), SKILL_EXTRAS[name] ?? {}),
    );
  }
  for (const name of readdirSync(join(REPO, 'agents')).sort()) {
    if (!name.endsWith('.md')) continue;
    const text = readFileSync(join(REPO, 'agents', name), 'utf8');
    files.set(join('agents', name), withFrontMatter(text, AGENT_EXTRAS[name.slice(0, -3)] ?? {}));
  }
  files.set(join('agents', 'executor-tier1.md'), agent(1));
  files.set(join('agents', 'executor-tier2.md'), agent(2));
  return files;
}

/** What differs between the plugin on disk and the build. */
export function staleFiles() {
  const want = expectedFiles();
  /** @type {string[]} */
  const stale = [];
  for (const [path, content] of want) {
    const full = join(PLUGIN, path);
    if (!existsSync(full) || !readFileSync(full).equals(Buffer.from(content))) stale.push(path);
  }
  for (const dir of OWNED) {
    for (const f of walk(join(PLUGIN, dir))) {
      const path = join(dir, f);
      if (!want.has(path)) stale.push(`${path} (not in the build)`);
    }
  }
  return stale;
}

/** Write the plugin. @returns {{ written: number }} */
export function buildPlugin() {
  const want = expectedFiles();
  for (const dir of OWNED) rmSync(join(PLUGIN, dir), { recursive: true, force: true });
  for (const [path, content] of want) {
    const full = join(PLUGIN, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
  return { written: want.size };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const stale = staleFiles();
    if (stale.length) {
      process.stdout.write(
        `The plugin is out of date (run npm run build):\n${stale.map((s) => `  ${s}`).join('\n')}\n`,
      );
      process.exitCode = 1;
    } else {
      process.stdout.write('The plugin is up to date.\n');
    }
  } else {
    const { written } = buildPlugin();
    process.stdout.write(
      `Wrote ${written} files to ${relative(process.cwd(), PLUGIN) || PLUGIN}.\n`,
    );
  }
}
